#ifndef PISTORM_RTG64_PROTOCOL_H
#define PISTORM_RTG64_PROTOCOL_H

#include <stdint.h>

#define RTG64_MMIO_SIZE 0x00010000u
#define RTG64_PROTOCOL_MAGIC 0x52544736u /* 'RTG6' */
#define RTG64_PROTOCOL_VERSION 0x00010000u

enum rtg64_register {
  RTG64_REG_MAGIC = 0x0000,
  RTG64_REG_VERSION = 0x0004,
  RTG64_REG_FEATURES = 0x0008,
  RTG64_REG_STATUS = 0x000C,
  RTG64_REG_CMD = 0x0010,
  RTG64_REG_ARG0 = 0x0014,
  RTG64_REG_ARG1 = 0x0018,
  RTG64_REG_ARG2 = 0x001C,
  RTG64_REG_ARG3 = 0x0020,
  RTG64_REG_ARG4 = 0x0024,
  RTG64_REG_ARG5 = 0x0028,
  RTG64_REG_ARG6 = 0x002C,
  RTG64_REG_ARG7 = 0x0030,
  RTG64_REG_RESULT = 0x0034,
  RTG64_REG_DEBUG = 0x0038,
};

enum rtg64_feature_flags {
  RTG64_FEATURE_MAILBOX = (1u << 0),
  RTG64_FEATURE_SHARED_FB = (1u << 1),
  RTG64_FEATURE_PALETTE = (1u << 2),
  RTG64_FEATURE_BENCH = (1u << 3),
};

enum rtg64_status_flags {
  RTG64_STATUS_READY = (1u << 0),
  RTG64_STATUS_FB_ALLOC = (1u << 1),
  RTG64_STATUS_MODE_SET = (1u << 2),
  RTG64_STATUS_ERROR = (1u << 31),
};

enum rtg64_command {
  RTG64_CMD_NONE = 0,
  RTG64_CMD_INIT = 1,
  RTG64_CMD_SET_MODE = 2,
  RTG64_CMD_ALLOC_FB = 3,
  RTG64_CMD_FREE_FB = 4,
  RTG64_CMD_FILL_RECT = 5,
  RTG64_CMD_BLIT_RECT = 6,
  RTG64_CMD_SET_PALETTE = 7,
  RTG64_CMD_PRESENT = 8,

  RTG64_CMD_BENCH_PATTERN = 0x80,
  RTG64_CMD_BENCH_SCROLL = 0x81,
};

enum rtg64_result {
  RTG64_RES_OK = 0,
  RTG64_RES_BAD_CMD = 1,
  RTG64_RES_BAD_ARG = 2,
  RTG64_RES_NO_MEM = 3,
  RTG64_RES_NOT_READY = 4,
  RTG64_RES_FAILED = 0xFF,
};

enum rtg64_pixel_format {
  RTG64_FMT_CLUT8 = 1,
  RTG64_FMT_RGB565 = 2,
  RTG64_FMT_XRGB8888 = 3,
  RTG64_FMT_ARGB8888 = 4,
};

#endif
