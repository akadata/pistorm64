#ifndef Z2_ARM64_ACCEL_REGS_H
#define Z2_ARM64_ACCEL_REGS_H

#include <stdint.h>

/*
 * ARM64 offload accelerator (Z2) Phase 1 contract:
 * - 0x0000-0x0FFF: register window
 * - 0x1000-0x1FFF: mailbox page
 * - 0x2000-...   : shared window
 */
#define ARM64_ACCEL_MANUFACTURER_ID 0x07DBu
#define ARM64_ACCEL_PRODUCT_ID      0x0041u

#define ARM64_ACCEL_Z2_SIZE         (4u * 1024u * 1024u)
#define ARM64_ACCEL_REG_WINDOW_SIZE 0x1000u
#define ARM64_ACCEL_MAILBOX_OFFSET  0x1000u
#define ARM64_ACCEL_MAILBOX_SIZE    0x1000u
#define ARM64_ACCEL_SHARED_OFFSET   0x2000u
#define ARM64_ACCEL_SHARED_SIZE     (ARM64_ACCEL_Z2_SIZE - ARM64_ACCEL_SHARED_OFFSET)

/*
 * Shared info block at start of shared window. Fields are 32-bit big-endian.
 */
#define ARM64_ACCEL_SHARED_INFO_OFFSET           ARM64_ACCEL_SHARED_OFFSET
#define ARM64_ACCEL_SHARED_INFO_SIZE             0x20u
#define ARM64_ACCEL_SHARED_INFO_OFF_SIGNATURE    0x00u
#define ARM64_ACCEL_SHARED_INFO_OFF_ABI_VERSION  0x04u
#define ARM64_ACCEL_SHARED_INFO_OFF_MB_OFFSET    0x08u
#define ARM64_ACCEL_SHARED_INFO_OFF_MB_SIZE      0x0Cu
#define ARM64_ACCEL_SHARED_INFO_OFF_JOBDESC_OFF  0x10u
#define ARM64_ACCEL_SHARED_INFO_OFF_JOBDESC_SIZE 0x14u
#define ARM64_ACCEL_SHARED_INFO_OFF_FEATURES     0x18u
#define ARM64_ACCEL_SHARED_INFO_OFF_RESERVED0    0x1Cu

#define ARM64_ACCEL_SHARED_INFO_SIGNATURE        0x41524D41u /* "ARMA" */
#define ARM64_ACCEL_SHARED_INFO_ABI_VERSION      1u
#define ARM64_ACCEL_SHARED_INFO_FEAT_MAILBOX     0x00000001u
#define ARM64_ACCEL_SHARED_INFO_FEAT_IRQ         0x00000002u
#define ARM64_ACCEL_SHARED_INFO_FEAT_SHARED_RAM  0x00000004u

#define ARM64_ACCEL_JOBDESC_OFFSET               (ARM64_ACCEL_SHARED_OFFSET + 0x0040u)
#define ARM64_ACCEL_JOBDESC_SIZE                 0x0100u

/* Job descriptor (big-endian 32-bit fields) at ARM64_ACCEL_JOBDESC_OFFSET. */
#define ARM64_ACCEL_JOBDESC_MAGIC                0x414A4F42u /* "AJOB" */
#define ARM64_ACCEL_JOBDESC_VERSION              1u
#define ARM64_ACCEL_JOBDESC_OFF_MAGIC            0x00u
#define ARM64_ACCEL_JOBDESC_OFF_VERSION          0x04u
#define ARM64_ACCEL_JOBDESC_OFF_STATE            0x08u
#define ARM64_ACCEL_JOBDESC_OFF_FLAGS            0x0Cu
#define ARM64_ACCEL_JOBDESC_OFF_ELF_OFFSET       0x10u
#define ARM64_ACCEL_JOBDESC_OFF_ELF_SIZE         0x14u
#define ARM64_ACCEL_JOBDESC_OFF_ENTRY_ARG        0x18u
#define ARM64_ACCEL_JOBDESC_OFF_RETVAL_LO        0x1Cu
#define ARM64_ACCEL_JOBDESC_OFF_RETVAL_HI        0x20u
#define ARM64_ACCEL_JOBDESC_OFF_RESULT           0x24u

#define ARM64_ACCEL_JOBDESC_STATE_IDLE           0u
#define ARM64_ACCEL_JOBDESC_STATE_QUEUED         1u
#define ARM64_ACCEL_JOBDESC_STATE_RUNNING        2u
#define ARM64_ACCEL_JOBDESC_STATE_DONE           3u
#define ARM64_ACCEL_JOBDESC_STATE_ERROR          4u

#define ARM64_ACCEL_JOBDESC_RESULT_OK            0u
#define ARM64_ACCEL_JOBDESC_RESULT_ERR_FORMAT    1u
#define ARM64_ACCEL_JOBDESC_RESULT_ERR_RANGE     2u
#define ARM64_ACCEL_JOBDESC_RESULT_ERR_LOAD      3u
#define ARM64_ACCEL_JOBDESC_RESULT_ERR_EXEC      4u
#define ARM64_ACCEL_JOBDESC_RESULT_ERR_INTERNAL  5u

#define ARM64_ACCEL_REG_MAGIC          0x0000u
#define ARM64_ACCEL_REG_ABI_VERSION    0x0004u
#define ARM64_ACCEL_REG_CONTROL        0x0008u
#define ARM64_ACCEL_REG_STATUS         0x000Cu
#define ARM64_ACCEL_REG_IRQ_STATUS     0x0010u
#define ARM64_ACCEL_REG_IRQ_ACK        0x0014u
#define ARM64_ACCEL_REG_MAILBOX_OFFSET 0x0018u
#define ARM64_ACCEL_REG_MAILBOX_SIZE   0x001Cu
#define ARM64_ACCEL_REG_SHARED_OFFSET  0x0020u
#define ARM64_ACCEL_REG_SHARED_SIZE    0x0024u
#define ARM64_ACCEL_REG_JOBDESC_OFFSET 0x0028u
#define ARM64_ACCEL_REG_JOBDESC_SIZE   0x002Cu
#define ARM64_ACCEL_REG_HEARTBEAT      0x0030u

#define ARM64_ACCEL_MAGIC              0x41524D41u /* "ARMA" */
#define ARM64_ACCEL_ABI_VERSION        1u

#define ARM64_ACCEL_CTRL_START         0x00000001u
#define ARM64_ACCEL_CTRL_STOP          0x00000002u
#define ARM64_ACCEL_CTRL_RESET         0x00000004u
#define ARM64_ACCEL_CTRL_IRQ_ENABLE    0x00000008u

#define ARM64_ACCEL_STATUS_READY       0x00000001u
#define ARM64_ACCEL_STATUS_BUSY        0x00000002u
#define ARM64_ACCEL_STATUS_FAULT       0x00000004u

#define ARM64_ACCEL_IRQ_JOB_DONE       0x00000001u
#define ARM64_ACCEL_IRQ_HOST_EVENT     0x00000002u

/* Mailbox offsets from ARM64_ACCEL_MAILBOX_OFFSET */
#define ARM64_ACCEL_MB_OFF_MAGIC       0x0000u
#define ARM64_ACCEL_MB_OFF_VERSION     0x0004u
#define ARM64_ACCEL_MB_OFF_SEQ         0x0008u
#define ARM64_ACCEL_MB_OFF_ACK_SEQ     0x000Cu
#define ARM64_ACCEL_MB_OFF_CMD         0x0010u
#define ARM64_ACCEL_MB_OFF_STATUS      0x0014u
#define ARM64_ACCEL_MB_OFF_ARG0        0x0018u
#define ARM64_ACCEL_MB_OFF_ARG1        0x001Cu
#define ARM64_ACCEL_MB_OFF_ARG2        0x0020u
#define ARM64_ACCEL_MB_OFF_ARG3        0x0024u
#define ARM64_ACCEL_MB_OFF_RESULT0     0x0028u
#define ARM64_ACCEL_MB_OFF_RESULT1     0x002Cu

#define ARM64_ACCEL_MB_MAGIC           0x414D4231u /* "AMB1" */
#define ARM64_ACCEL_MB_VERSION         1u

#define ARM64_ACCEL_MB_CMD_NONE        0u
#define ARM64_ACCEL_MB_CMD_PING        1u
#define ARM64_ACCEL_MB_CMD_RUN_ELF     2u

#define ARM64_ACCEL_MB_STATUS_IDLE     0u
#define ARM64_ACCEL_MB_STATUS_BUSY     1u
#define ARM64_ACCEL_MB_STATUS_DONE     2u
#define ARM64_ACCEL_MB_STATUS_ERR      3u

#endif
